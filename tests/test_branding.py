"""No watermarks or AI/Muse branding anywhere in the shipped files."""

import os

ROOT = os.path.join(os.path.dirname(__file__), "..")
FORBIDDEN = ("Muse", "Claude", "Anthropic", "AI-generated", "generated by AI",
             "watermark", "as an AI")
SCAN_DIRS = ("src", "scripts", "tests", ".github")
SCAN_FILES = ("README.md", "demo.py", "pyproject.toml")


def _files():
    for d in SCAN_DIRS:
        for base, _dirs, files in os.walk(os.path.join(ROOT, d)):
            if "__pycache__" in base:
                continue
            for f in files:
                # This test itself lists the forbidden tokens; never scan it.
                if f == "test_branding.py" or f.endswith(".pyc"):
                    continue
                yield os.path.join(base, f)
    for f in SCAN_FILES:
        yield os.path.join(ROOT, f)


def test_no_branding():
    bad = []
    for path in _files():
        if not os.path.isfile(path):
            continue
        with open(path, errors="ignore") as fh:
            text = fh.read()
        for token in FORBIDDEN:
            if token in text:
                bad.append(f"{path}: {token!r}")
    assert not bad, "; ".join(bad)
